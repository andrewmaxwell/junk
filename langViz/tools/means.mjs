// Average output of every knockable component over real KJV text, for
// mean-ablation. A knocked-out part then writes its USUAL output whatever the
// text says, rather than zeros the model never saw in training.
//
//   node langViz/tools/means.mjs        (re-run after every retrain)
//
// Writes ablation_means.json: per block the mean attention write, MLP write and
// pre-W_O head outputs, averaged over every position of WINDOWS random 64-token
// windows of the corpus (seeded, so the file is reproducible).
import {readFile, writeFile} from 'fs/promises';
import {ROOT, loaded, tokenizer, makeWith} from './node-model.mjs';

const WINDOWS = 600;
const {n_layers: L, d_model: D, block_size: T} = loaded.config;
const text = await readFile(ROOT + '../jibberjabber/bible.txt', 'utf8');
const ids = tokenizer.encode(text);
const model = makeWith(null);

let seed = 1337;
const rand = () => (seed = (seed * 1103515245 + 12345) >>> 0) / 2 ** 32;
const sum = () => Array.from({length: L}, () => new Float64Array(D));
const acc = {attn: sum(), mlp: sum(), heads: sum()};
for (let w = 0; w < WINDOWS; w++) {
  const s = Math.floor(rand() * (ids.length - T));
  const {activations} = model.forward(ids.slice(s, s + T));
  activations.layers.forEach((lay, l) => {
    for (let i = 0; i < T * D; i++) {
      acc.attn[l][i % D] += lay.attn_write[i];
      acc.mlp[l][i % D] += lay.mlp_write[i];
      acc.heads[l][i % D] += lay.attnOut[i];
    }
  });
}
const n = WINDOWS * T;
// ties the file to these exact weights (same rule the page checks)
export const fingerprint = (tensors) =>
  Array.from(tensors.get('ln_f.w').slice(0, 6), (x) => +x.toFixed(4)).join(',');
const round = (rows) =>
  rows.map((r) => Array.from(r, (x) => +(x / n).toFixed(6)));
const out = {
  note: 'Mean component outputs over KJV text, for mean-ablation knockouts. Generated by tools/means.mjs; re-run after retraining.',
  n_layers: L,
  d_model: D,
  positions: n,
  fingerprint: fingerprint(loaded.tensors),
  attn: round(acc.attn),
  mlp: round(acc.mlp),
  heads: round(acc.heads),
};
await writeFile(ROOT + 'ablation_means.json', JSON.stringify(out));
console.log(
  `ablation_means.json: ${n.toLocaleString()} positions from ${ids.length.toLocaleString()} corpus tokens`,
);
